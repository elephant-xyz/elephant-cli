//! The UnixFS CID of a file as `ipfs add --cid-version 1 --raw-leaves` (kubo)
//! and ipfs-unixfs-importer compute it: 262144-byte raw leaves under a
//! balanced dag-pb tree of up to 174 links per node. Blocks are hashed, not kept.

use crate::car::leb;
use crate::cids;
use crate::Fail;
use cid::Cid;
use std::io::Read;

const CHUNK: usize = 262_144;
const WIDTH: usize = 174;
const DAG_PB: u64 = 0x70;

/// A node of the tree: its CID, the bytes of the DAG below it, the file bytes it covers.
struct Node {
    cid: Cid,
    total: u64,
    covers: u64,
}

/// The dag-pb file node linking `children` in order.
fn parent(children: &[Node]) -> Node {
    let covers = children.iter().map(|child| child.covers).sum();
    // UnixFS: type File, the file size, then the size each child covers
    let mut data = vec![0x08, 0x02, 0x18];
    leb(covers, &mut data);
    for child in children {
        data.push(0x20);
        leb(child.covers, &mut data);
    }
    let mut block = Vec::new();
    for child in children {
        let hash = child.cid.to_bytes();
        // a link: the hash, an empty name, the size of the DAG below it
        let mut link = vec![0x0a];
        leb(hash.len() as u64, &mut link);
        link.extend(hash);
        link.extend([0x12, 0x00, 0x18]);
        leb(child.total, &mut link);
        block.push(0x12);
        leb(link.len() as u64, &mut block);
        block.extend(link);
    }
    block.push(0x0a);
    leb(data.len() as u64, &mut block);
    block.extend(data);
    let below: u64 = children.iter().map(|child| child.total).sum();
    Node { cid: cids::of(DAG_PB, &block), total: block.len() as u64 + below, covers }
}

pub fn cid(mut source: impl Read) -> Result<Cid, Fail> {
    let mut level = Vec::new();
    let mut chunk = vec![0u8; CHUNK];
    loop {
        let mut filled = 0;
        while filled < CHUNK {
            match source.read(&mut chunk[filled..])? {
                0 => break,
                read => filled += read,
            }
        }
        if filled > 0 || level.is_empty() {
            level.push(Node { cid: cids::of(cids::RAW, &chunk[..filled]), total: filled as u64, covers: filled as u64 });
        }
        if filled < CHUNK {
            break;
        }
    }
    // A file of one chunk is that chunk; anything longer gets parents until one node is left.
    while level.len() > 1 || (level[0].cid.codec() == cids::RAW && level[0].covers > CHUNK as u64) {
        level = level.chunks(WIDTH).map(parent).collect();
        if level.len() == 1 {
            break;
        }
    }
    Ok(level.remove(0).cid)
}

#[cfg(test)]
mod tests {
    /// CIDs ipfs-unixfs-importer 15.4.0 gives the same generated bytes with
    /// `{cidVersion: 1, rawLeaves: true}`, as elephant-cli 1.58.1 called it.
    #[test]
    fn matches_the_importer_elephant_cli_1_used() {
        for (size, expected) in [
            (0usize, "bafkreihdwdcefgh4dqkjv67uzcmw7ojee6xedzdetojuzjevtenxquvyku"),
            (1, "bafkreigkgwdvr5wspzwpiutssn4xpj2i7wedshnwphhnu7ohx4pqaxxipe"),
            (262_144, "bafkreieiuj5mzeuqor24l4lmo2yumm6665yv4gq7ozzp2nrfmqrjyboosy"),
            (262_145, "bafybeich6cqd6yabw3cku6edwmz4rvwe275nx2l6ootvc2bpbt5bdvarua"),
            (1_000_000, "bafybeiclwhwdl4p5zj7tkk4w4xwcnphz76aibkikjcfmx7cecdfjdtlstq"),
            (174 * 262_144, "bafybeiafkae3md3zfgdgpk2ztpkul5dzotu4bgbnvuinadceqrqa2rz7bi"),
            (174 * 262_144 + 1, "bafybeibo5yjphmmdq6aigqtgrijost25l5lmv5l37von7hrjv7sagnx4sy"),
        ] {
            let bytes: Vec<u8> = (0..size).map(|at| ((at * 31 + 7) % 251) as u8).collect();
            assert_eq!(super::cid(bytes.as_slice()).unwrap().to_string(), expected, "{size} bytes");
        }
    }
}
